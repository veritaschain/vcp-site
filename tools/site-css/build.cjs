'use strict';

const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const { ROOT, ASSET, manifest, validate, compileTheme, scoped, namespaceKeyframes, compact, sha256 } = require('./lib.cjs');

async function build() {
  const man = manifest();
  const count = validate(man);
  const chunks = ['/*! Tailwind CSS v3.4.17 | MIT License | https://tailwindcss.com */\n/* Generated by tools/site-css/build.cjs; edit the sources, not this file. */\n'];
  const keyframes = new Map();
  for (const [id, theme] of Object.entries(man.themes)) {
    const root = scoped(namespaceKeyframes(await compileTheme(theme), id), id);
    root.walkAtRules(/keyframes$/, rule => {
      const key = `${rule.name}:${rule.params}`;
      const value = compact(rule);
      if (keyframes.has(key)) {
        if (keyframes.get(key) !== value) throw new Error(`Conflicting global animation ${key}; isolate it before building`);
        rule.remove();
      } else keyframes.set(key, value);
    });
    chunks.push(`/* theme: ${id} */\n${compact(root)}\n`);
  }
  const output = chunks.join('');
  const target = path.join(ROOT, ASSET);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error(`${ASSET} is stale; run npm run build --prefix tools/site-css`);
  } else fs.writeFileSync(target, output);
  console.log(JSON.stringify({ pagesAndTemplates: count, themes: Object.keys(man.themes).length, bytes: Buffer.byteLength(output), gzipBytes: zlib.gzipSync(output).length, sha256: sha256(output) }));
}

if (require.main === module) build().catch(error => { console.error(error); process.exitCode = 1; });
module.exports = { build };
