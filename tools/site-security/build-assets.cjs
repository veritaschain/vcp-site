'use strict';

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const esbuild = require('esbuild');
const babel = require('@babel/standalone');

const ROOT = path.resolve(__dirname, '../..');
const TARGET = 'assets/vendor/qrcode-1.5.3.min.js';
const NOTICE = 'assets/vendor/qrcode-LICENSE.txt';
const check = process.argv.includes('--check');

function output(file, text) {
  const absolute = path.join(ROOT, file);
  if (check) {
    if (!fs.existsSync(absolute) || fs.readFileSync(absolute, 'utf8') !== text) throw new Error(`Stale generated asset: ${file}`);
  } else {
    fs.mkdirSync(path.dirname(absolute), { recursive: true });
    fs.writeFileSync(absolute, text);
  }
}

async function main() {
  const result = await esbuild.build({
    absWorkingDir: ROOT,
    entryPoints: [path.join(__dirname, 'node_modules/qrcode/lib/browser.js')],
    bundle: true, platform: 'browser', format: 'iife', globalName: 'QRCode',
    target: ['es2018'], minify: true, write: false, metafile: true, legalComments: 'none',
    banner: { js: '/*! qrcode 1.5.3 browser bundle; MIT licenses: /assets/vendor/qrcode-LICENSE.txt; generated by tools/site-security/build-assets.cjs */' }
  });
  const dependencies = new Set(Object.keys(result.metafile.inputs).map(file => file.match(/node_modules\/([^/]+)\//)?.[1]));
  const licenses = { qrcode: 'license', dijkstrajs: 'LICENSE.md', 'encode-utf8': null };
  for (const name of dependencies) if (!(name in licenses)) throw new Error(`Review the bundled dependency and license: ${name}`);
  const notices = [...dependencies].sort().map(name => {
    const dir = path.join(__dirname, 'node_modules', name);
    const version = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')).version;
    const notice = fs.readFileSync(licenses[name] ? path.join(dir, licenses[name]) : path.join(__dirname, 'encode-utf8-NOTICE.txt'), 'utf8');
    return `${name} ${version}\n${'='.repeat(name.length + version.length + 1)}\n\n${notice.trim()}\n`;
  }).join('\n');
  const code = result.outputFiles[0].text;
  output(TARGET, code);
  output(NOTICE, notices);
  const jsx = fs.readFileSync(path.join(ROOT, 'vcc/demo/app.jsx'), 'utf8');
  // Match the previous Babel 8 standalone script's env + classic React presets.
  // JSX compilation now happens during the build, not in the visitor's browser.
  const app = babel.transform(jsx, { presets: [['env'], ['react', { runtime: 'classic', development: false }]], sourceMaps: false,
    sourceType: 'script', comments: false, filename: 'vcc-demo-app.jsx' }).code;
  output('vcc/demo/app.js', '/* Generated from app.jsx by tools/site-security/build-assets.cjs (Babel 8.1.0). */\n' + app + '\n');
  console.log(JSON.stringify({ asset: TARGET, bytes: Buffer.byteLength(code), integrity: 'sha384-' + crypto.createHash('sha384').update(code).digest('base64'), dependencies: [...dependencies].sort() }));
}

main().catch(error => { console.error(error); process.exitCode = 1; });
