#!/usr/bin/env python3
"""Build/check narrowly mapped legacy URLs reported as missing in Search Console.

Usage: python3 scripts/build-legacy-aliases.py build | check
GitHub Pages serves these HTML redirects; they are not HTTP 301 responses.
The canonical destination remains indexable, while aliases stay out of sitemap.xml.
"""
import html
import json
import sys
from html.parser import HTMLParser
from pathlib import Path

from seo import ROOT, ORIGIN, NS, Page, page_path, sitemap_entries

MANIFEST = Path(__file__).with_name('legacy-aliases.json')
MARKER = '<!-- Generated by scripts/build-legacy-aliases.py; edit legacy-aliases.json. -->'
COPY = {
    'en': ('Page moved', 'Continue to the current page.', 'English'),
    'ja': ('ページの移転先', '現在のページへ移動します。自動で移動しない場合は、以下のリンクをご利用ください。', '英語版 / English'),
    'zh-CN': ('页面已迁移', '正在前往当前页面。如果没有自动跳转，请使用下面的链接。', '英文版 / English'),
}
STYLE = 'body{margin:0;background:#0b1020;color:#e2e8f0;font:1rem/1.75 system-ui,sans-serif}main{max-width:48rem;margin:10vh auto;padding:2rem}a{color:#a5d3ff;text-underline-offset:.2em}a:focus-visible{outline:3px solid #c4b5fd;outline-offset:5px}h1{line-height:1.25}p{overflow-wrap:anywhere}.brand{color:#c4b5fd;font-size:.85rem}.note{color:#b7c4d8}'


class RedirectPage(HTMLParser):
    def __init__(self, text):
        super().__init__()
        self.refresh = []
        self.feed(text)

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'meta' and attrs.get('http-equiv', '').lower() == 'refresh':
            self.refresh.append(attrs.get('content', ''))


def validate_manifest():
    rows = json.loads(MANIFEST.read_text(encoding='utf-8'))
    sources = [row['source'] for row in rows]
    if len(sources) != len(set(sources)):
        raise ValueError('Duplicate legacy source')
    sitemap_urls = {entry.findtext(f'{{{NS}}}loc') for entry in sitemap_entries()}
    for row in rows:
        for key in ('source', 'target'):
            route = row[key]
            if not route.startswith('/') or not route.endswith('/') or '?' in route or '#' in route:
                raise ValueError('Expected a root-relative directory route: ' + route)
            page_path(ORIGIN + route)
        if row['target'] in sources:
            raise ValueError('Alias chains are not permitted: ' + row['source'])
        if ORIGIN + row['source'] in sitemap_urls:
            raise ValueError('Alias must not appear in sitemap.xml: ' + row['source'])
        target = Page(page_path(ORIGIN + row['target']))
        if not target.indexable or target.canonical != [ORIGIN + row['target']]:
            raise ValueError('Target must be indexable and self-canonical: ' + row['target'])
        if target.lang != row['target_language']:
            raise ValueError('Destination language does not match: ' + row['target'])
        row['title'] = target.title
    return rows


def render(row):
    destination = ORIGIN + row['target']
    heading, message, english_label = COPY[row['language']]
    english_fallback = row['language'] != 'en' and row['target_language'] == 'en'
    label = row['title'] + (f' ({english_label})' if english_fallback else '')
    if english_fallback:
        message += (' このURLの翻訳版は公開されていないため、英語の記事をご案内します。'
                    if row['language'] == 'ja' else '此网址没有已发布的翻译版本，链接将打开英文文章。')
    return f'''<!DOCTYPE html>
{MARKER}
<html lang="{row['language']}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{html.escape(heading)} | VSO</title>
  <meta http-equiv="refresh" content="0; url={html.escape(destination, quote=True)}">
  <link rel="canonical" href="{html.escape(destination, quote=True)}">
  <link rel="icon" href="/favicon.ico">
  <style>{STYLE}</style>
</head>
<body><main>
  <p class="brand">VeritasChain Standards Organization (VSO)</p>
  <h1>{html.escape(heading)}</h1>
  <p>{html.escape(message)}</p>
  <p><a href="{html.escape(destination, quote=True)}" lang="{row['target_language']}">{html.escape(label)}</a></p>
</main></body>
</html>
'''


def main():
    if len(sys.argv) != 2 or sys.argv[1] not in ('build', 'check'):
        raise SystemExit(__doc__)
    rows = validate_manifest()
    for row in rows:
        destination = page_path(ORIGIN + row['source'])
        if sys.argv[1] == 'build':
            if destination.exists() and MARKER not in destination.read_text(encoding='utf-8'):
                raise ValueError('Refusing to overwrite a non-generated page: ' + row['source'])
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(render(row), encoding='utf-8')
        text = destination.read_text(encoding='utf-8')
        page = Page(destination)
        target = ORIGIN + row['target']
        if (text != render(row) or page.canonical != [target]
                or not page.indexable or target not in page.refs
                or RedirectPage(text).refresh != ['0; url=' + target]):
            raise ValueError('Stale or invalid alias: ' + row['source'])
    not_found = ROOT / '404.html'
    if not_found.exists():
        page = Page(not_found)
        if page.canonical or RedirectPage(not_found.read_text(encoding='utf-8')).refresh:
            raise ValueError('404 page must not redirect or canonicalize missing URLs')
        for link in ('/', '/sitemap/', '/support/'):
            if link not in page.refs:
                raise ValueError('Missing recovery link on 404 page: ' + link)
    print(json.dumps({'legacy_aliases': len(rows), 'destination_checks': 'passed',
                      'excluded_from_sitemap': True, 'mechanism': 'HTML meta refresh, not HTTP 301'}))


if __name__ == '__main__':
    main()
